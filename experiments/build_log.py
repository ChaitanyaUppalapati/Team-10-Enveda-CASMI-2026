"""Combine experiments/entries/*.yaml into LOG.md (+ score_over_time.png). Owner: Member 1.

Usage: python experiments/build_log.py [--entries DIR] [--out LOG.md] [--no-plot]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
import yaml

HERE = Path(__file__).resolve().parent
REQUIRED = ("date", "member", "model_id", "version", "change", "val_mrr", "lb_score")


def load_entries(entries_dir: Path) -> pd.DataFrame:
    """Read every entry, check required keys, and return a table sorted by date."""
    rows = []
    for path in sorted(entries_dir.glob("*.yaml")):
        entry = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        missing = [k for k in REQUIRED if k not in entry]
        if missing:
            raise ValueError(f"{path.name}: missing keys {missing}")
        entry["file"] = path.name
        rows.append(entry)
    cols = [*REQUIRED, "submitted", "notes", "file"]
    df = pd.DataFrame(rows, columns=cols)
    if df.empty:
        return df
    df["date"] = pd.to_datetime(df["date"]).dt.date
    return df.sort_values(["date", "member", "model_id"]).reset_index(drop=True)


def to_markdown(df: pd.DataFrame) -> str:
    """Render the log as a Markdown table plus the best score per model."""
    head = "# Experiment log\n\nGenerated by `python experiments/build_log.py`; do not edit.\n\n"
    if df.empty:
        return head + "_No entries yet._\n"
    show = ["date", "member", "model_id", "version", "change", "val_mrr", "lb_score"]
    lines = ["| " + " | ".join(show) + " |", "|" + "---|" * len(show)]
    for _, r in df.iterrows():
        cells = ["" if pd.isna(r[c]) else str(r[c]).replace("|", "/") for c in show]
        lines.append("| " + " | ".join(cells) + " |")
    best = (
        df.dropna(subset=["val_mrr"])
        .sort_values("val_mrr", ascending=False)
        .drop_duplicates("model_id")[["model_id", "member", "val_mrr", "lb_score"]]
    )
    out = head + "## All runs\n\n" + "\n".join(lines) + "\n"
    if not best.empty:
        out += "\n## Best val MRR@25 per model\n\n| model_id | member | val_mrr | lb_score |\n"
        out += "|---|---|---|---|\n"
        for _, r in best.iterrows():
            lb = "" if pd.isna(r["lb_score"]) else r["lb_score"]
            out += f"| {r['model_id']} | {r['member']} | {r['val_mrr']} | {lb} |\n"
    return out


def plot(df: pd.DataFrame, path: Path) -> bool:
    """Plot best-so-far val and LB scores over time. Returns False if matplotlib is missing."""
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return False
    fig, ax = plt.subplots(figsize=(7, 4))
    for col, label in (("val_mrr", "val MRR@25 (best so far)"), ("lb_score", "LB (best so far)")):
        s = df.dropna(subset=[col]).groupby("date")[col].max().cummax()
        if not s.empty:
            ax.plot(s.index, s.values, marker="o", label=label)
    ax.set_xlabel("date")
    ax.set_ylabel("MRR@25")
    ax.legend()
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return True


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--entries", type=Path, default=HERE / "entries")
    parser.add_argument("--out", type=Path, default=HERE / "LOG.md")
    parser.add_argument("--no-plot", action="store_true")
    args = parser.parse_args(argv)
    df = load_entries(args.entries)
    args.out.write_text(to_markdown(df), encoding="utf-8")
    print(f"wrote {args.out} ({len(df)} entries)")
    if not args.no_plot and not df.empty and plot(df, args.out.with_name("score_over_time.png")):
        print("wrote score_over_time.png")


if __name__ == "__main__":
    main()
